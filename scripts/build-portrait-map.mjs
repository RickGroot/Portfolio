#!/usr/bin/env node
/*
 * Turns the portrait into a luminance map the character field can render, and a
 * pre-resolved static frame for the no-JS and reduced-motion paths.
 *
 * Runs at BUILD time and commits its output, matching the policy already used
 * for fonts in docs/performance.md ("deliberately no font build dependency").
 * The alternative -- an Astro integration writing into src/ -- fights the dev
 * server's file watcher and costs seconds on every `astro dev` for an asset that
 * changes roughly never.
 *
 * The emitted artifact is a 12-level greyscale map. It carries no EXIF, no GPS
 * and no camera metadata, because it is not an image any more.
 *
 * Run:  node scripts/build-portrait-map.mjs
 * Out:  src/generated/portrait-map.ts
 */

import sharp from 'sharp';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const SOURCE = 'src/assets/portrait-placeholder.png';
const OUT = 'src/generated/portrait-map.ts';

/* Tuning. Echoed into the output so the hash covers them. */
const PARAMS = {
	/** Square map; resampled into cell space at runtime. 80 covers a 100-col
	 *  portrait box with at most 1.25x upsampling, which is invisible. */
	size: 80,
	/** More levels than the ramp has, so we never quantise twice. */
	levels: 12,
	/** Removes high-frequency detail deflate cannot compress. ~20% smaller,
	 *  and at this resolution it costs nothing visually. */
	blur: 0.6,
	/** Static frame dimensions. Characters are ~2x taller than wide. */
	staticCols: 64,
	staticAspect: 0.5,
};

/** Level index -> character. Must match RAMP in src/lib/field/field.ts. */
const RAMP = ' .:-=+*#%@';

/** 12 printable symbols, one per level. Compresses far better than base64:
 *  measured 3x smaller than base64 and 3.8x smaller than a JSON array,
 *  because a small alphabet keeps deflate's match-finding working. */
const ALPHABET = '0123456789ab';

const sourceBytes = readFileSync(SOURCE);
const sha = createHash('sha256')
	.update(sourceBytes)
	.update(JSON.stringify(PARAMS))
	.digest('hex')
	.slice(0, 16);

/** Greyscale, contrast-stretched, blurred, square. */
async function luminance(cols, rows) {
	const { data, info } = await sharp(SOURCE)
		.rotate() // honour EXIF orientation before anything else
		.greyscale()
		.normalise() // stretch the histogram; a muddy ramp is a muddy histogram
		.blur(PARAMS.blur)
		.resize(cols, rows, { fit: 'fill' })
		.removeAlpha()
		.raw()
		.toBuffer({ resolveWithObject: true });
	return { data, w: info.width, h: info.height };
}

/* ---- the map ------------------------------------------------------------ */

const { data: mapData } = await luminance(PARAMS.size, PARAMS.size);
let map = '';
for (let i = 0; i < mapData.length; i++) {
	const level = Math.min(PARAMS.levels - 1, ((mapData[i] / 255) * PARAMS.levels) | 0);
	map += ALPHABET[level];
}

/* ---- the static, fully-resolved frame ----------------------------------- */

const staticRows = Math.round(PARAMS.staticCols * PARAMS.staticAspect);
const { data: sData } = await luminance(PARAMS.staticCols, staticRows);
const lines = [];
for (let y = 0; y < staticRows; y++) {
	let line = '';
	for (let x = 0; x < PARAMS.staticCols; x++) {
		const v = sData[y * PARAMS.staticCols + x] / 255;
		line += RAMP[Math.min(RAMP.length - 1, (v * RAMP.length) | 0)];
	}
	lines.push(line);
}
const staticFrame = lines.join('\n');

/* ---- emit --------------------------------------------------------------- */

mkdirSync('src/generated', { recursive: true });

const banner = `// GENERATED by scripts/build-portrait-map.mjs -- do not edit.
// Source: ${SOURCE}
// Regenerate: node scripts/build-portrait-map.mjs
`;

writeFileSync(
	OUT,
	`${banner}
/** sha256 of the source image + params. check-assets.mjs fails on drift. */
export const SOURCE_SHA = '${sha}';

export const MAP_SIZE = ${PARAMS.size};
export const MAP_LEVELS = ${PARAMS.levels};
/** Level per cell, row-major, one character each from '${ALPHABET}'. */
export const MAP = '${map}';

/** Fully-resolved frame, rendered at build time.
 *  This is what no-JS and reduced-motion visitors see -- the real thing, not a
 *  placeholder. The renderer only ever takes over something already correct. */
export const STATIC_FRAME = ${JSON.stringify(staticFrame)};
export const STATIC_COLS = ${PARAMS.staticCols};
export const STATIC_ROWS = ${staticRows};
`,
);

const gz = (await import('node:zlib')).gzipSync(Buffer.from(map), { level: 9 }).length;
console.log(`wrote ${OUT}`);
console.log(`  map          ${PARAMS.size}x${PARAMS.size} @ ${PARAMS.levels} levels`);
console.log(`  map gzip     ${(gz / 1024).toFixed(2)} KB`);
console.log(`  static frame ${PARAMS.staticCols}x${staticRows}`);
console.log(`  source sha   ${sha}`);
